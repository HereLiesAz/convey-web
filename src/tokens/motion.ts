/**
 * Physics-first motion system — the web port of convey's `ConveyMotion`.
 *
 * Every spring here has a name that describes what it communicates to the user,
 * not how it behaves mathematically. "Snappy" because the user feels their touch
 * acknowledged immediately. "Deliberate" because slow motion signals weight and
 * consequence. "Elastic" because the overshoot communicates playfulness and life.
 *
 * The parameters are deliberate and are ported bit-for-bit from `convey`'s
 * `tokens/ConveyMotion.kt` (stiffness/dampingRatio pairs). Do not adjust them for
 * aesthetic reasons — if you need different motion, add a new named entry to your
 * `ConveyGrammar` instead of hand-tuning one of these.
 *
 * CSS has no native spring easing, so every `SpringSpec` here is realized as a CSS
 * `linear()` easing function (Baseline 2023+) generated by sampling a damped
 * harmonic oscillator — see `springToLinearEasing`. This keeps animation fully
 * declarative (a CSS `transition`/`animation` timing-function string), with no
 * per-frame JS stepping required, matching how a `SpringSpec` is just data until
 * Compose's own animation runtime samples it.
 */

/** A spring's physical parameters — identical fields to Compose's `SpringSpec`. */
export interface SpringSpec {
  readonly kind: 'spring'
  readonly stiffness: number
  readonly dampingRatio: number
}

/** A duration + CSS cubic-bezier easing pair — the web equivalent of Compose's `TweenSpec`. */
export interface TweenSpec {
  readonly kind: 'tween'
  readonly durationMillis: number
  /** A valid CSS `cubic-bezier(...)` or keyword easing string. */
  readonly easing: string
}

/** No animation. Error states interrupt; they do not ease. */
export interface SnapSpec {
  readonly kind: 'snap'
}

export type AnimationSpec = SpringSpec | TweenSpec | SnapSpec

function spring(stiffness: number, dampingRatio: number): SpringSpec {
  return { kind: 'spring', stiffness, dampingRatio }
}

function tween(durationMillis: number, easing: string): TweenSpec {
  return { kind: 'tween', durationMillis, easing }
}

function snap(): SnapSpec {
  return { kind: 'snap' }
}

