// ── Spring → CSS ────────────────────────────────────────────────────────────

/** True if this spring will overshoot its target before settling. */
export function isElastic(s: SpringSpec): boolean {
  return s.dampingRatio < 1
}

/** True if this spring is critically damped (no overshoot, fastest possible settling). */
export function isCriticallyDamped(s: SpringSpec): boolean {
  return s.dampingRatio >= 1
}

/** Estimated time to settle within `tolerance` of the target, in milliseconds. */
export function estimatedDurationMs(s: SpringSpec, tolerance = 0.01): number {
  if (s.dampingRatio >= 1) return Math.round(3000 / s.stiffness)
  const omega = Math.sqrt(s.stiffness)
  const decay = s.dampingRatio * omega
  if (decay === 0) return Number.MAX_SAFE_INTEGER
  return Math.round((-Math.log(tolerance) / decay) * 1000)
}

/**
 * Samples a unit-mass damped harmonic oscillator (the same model Compose's `spring()`
 * animates) and returns a CSS `linear()` easing function string reproducing that curve
 * over `durationMs` (default: this spring's own settle time, see `estimatedDurationMs`).
 *
 * Usage:
 * ```ts
 * el.style.transitionTimingFunction = springToLinearEasing(ConveyMotion.Snappy)
 * el.style.transitionDuration = `${estimatedDurationMs(ConveyMotion.Snappy)}ms`
 * ```
 *
 * `linear()` is Baseline 2023 (Chrome 113+, Firefox 112+, Safari 17.2+) — the only CSS
 * timing-function primitive expressive enough to encode an overshooting spring without
 * falling back to per-frame JavaScript. `steps` controls fidelity vs. string size; 24 is
 * enough for a springs this system uses (short, few-oscillation curves) to look correct
 * at typical UI sizes and durations.
 */
export function springToLinearEasing(s: SpringSpec, durationMs?: number, steps = 24): string {
  const duration = durationMs ?? estimatedDurationMs(s)
  const omega0 = Math.sqrt(s.stiffness)
  const zeta = s.dampingRatio

  const positionAt = (tMs: number): number => {
    const t = tMs / 1000
    if (zeta >= 1) {
      // Critically/over-damped: no oscillation.
      const omegaD = omega0 * Math.sqrt(zeta * zeta - 1)
      if (zeta === 1 || omegaD === 0) {
        return 1 - Math.exp(-omega0 * t) * (1 + omega0 * t)
      }
      const r1 = -omega0 * (zeta - Math.sqrt(zeta * zeta - 1))
      const r2 = -omega0 * (zeta + Math.sqrt(zeta * zeta - 1))
      const c2 = -r1 / (r2 - r1)
      const c1 = 1 - c2
      return 1 - (c1 * Math.exp(r1 * t) + c2 * Math.exp(r2 * t))
    }
    // Underdamped: decaying oscillation toward 1.
    const omegaD = omega0 * Math.sqrt(1 - zeta * zeta)
    const envelope = Math.exp(-zeta * omega0 * t)
    const phase = Math.cos(omegaD * t) + (zeta * omega0) / omegaD * Math.sin(omegaD * t)
    return 1 - envelope * phase
  }

  const stops: string[] = []
  for (let i = 0; i <= steps; i++) {
    const tMs = (i / steps) * duration
    const value = positionAt(tMs)
    stops.push(value.toFixed(4))
  }
  return `linear(${stops.join(', ')})`
}

/**
 * Resolves any `AnimationSpec` to a CSS `{ duration, easing }` pair ready for
 * `element.style.transitionDuration`/`transitionTimingFunction`, or for a Web Animations
 * API `KeyframeEffect` options object.
 */
export function toCss(specValue: AnimationSpec): { durationMs: number; easing: string } {
  switch (specValue.kind) {
    case 'spring':
      return { durationMs: estimatedDurationMs(specValue), easing: springToLinearEasing(specValue) }
    case 'tween':
      return { durationMs: specValue.durationMillis, easing: specValue.easing }
    case 'snap':
      return { durationMs: 0, easing: 'step-end' }
  }
}
